"""Конструкция главного героя Rogalik — мастер-образ (задача 3.1e, ревизия 3).

Метод: **мазковый художник** (`pxbrush.py`), а не формовый рендерер.
Каждая масса тела, каждая складка ткани и каждая прядь — отдельный мазок с
явно назначенным тоном рампы. Свет не вычисляется, а расставляется: тёплый
ключевой сверху-слева, глухая окклюзия в стыках, холодных «царапин» нет.

Ракурс: **three-quarter top-down**. Камера смотрит на героя сверху под углом
и чуть спереди-слева, поэтому:

* видна верхняя плоскость черепа и масса волос — она занимает ~0.20 H;
* плечи и трапеции — самые светлые плоскости кадра;
* торс и ноги сжаты по вертикали (перспектива), голова кажется крупной;
* ступни видны сверху, пальцы читаются.

Тональный порядок (главное отличие от 3.1d): **база — средний тон материала**,
свет ложится на верхние плоскости, тень остаётся только в стыках и складках.
Прежние версии заливали тело тёмным и рисовали свет линиями — отсюда «плоская
фигура с полосками».

Все координаты — в долях высоты фигуры H (0 = верх волос, 1 = подошвы),
поэтому одна и та же конструкция даёт согласованные 96 px и 48 px, а позже —
согласованные позы и кадры анимации.
"""

