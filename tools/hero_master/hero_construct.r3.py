    report = {}
    for height, detail in ((96, 1), (48, 0)):
        canvas = draw(height, detail)
        image = canvas.to_image()
        name = f"hero_master_{height}.png"
        path = os.path.join(out_dir, name)
        image.save(path)
        report[height] = canvas.report()
        report[height]["path"] = path
        preview = image.resize((image.width * 6, image.height * 6), Image.NEAREST)
        preview.save(os.path.join(ROOT, "reports",
                                  f"stage3e_preview_{height}_x6.png"))
        print(json.dumps({height: report[height]}, ensure_ascii=False))
    with open(os.path.join(ROOT, "reports", "stage3e_master_build.json"), "w",
              encoding="utf-8") as handle:
        json.dump(report, handle, ensure_ascii=False, indent=2)
    return 0


